    def normalize(self, text: str) -> str:
        """Applies rule-based Inverse Text Normalization to Russian speech text."""
        if not text:
            return ""

        res = text

        # 1. Dimensions (3×6, 6×3, etc.)
        for pattern, replacement in self.dimension_patterns:
            res = pattern.sub(replacement, res)

        # 2. Outdoor advertising terms
        for pattern, replacement in self.term_patterns:
            res = pattern.sub(replacement, res)

        # 3. Currency & Price rules
        for pattern, replacement in self.currency_patterns:
            res = pattern.sub(replacement, res)

        # 4. Dates & times
        for pattern, replacement in self.date_patterns:
            res = pattern.sub(replacement, res)
        for pattern, replacement in self.time_patterns:
            res = pattern.sub(replacement, res)

        # 5. Phone numbers
        for pattern, replacement in self.phone_patterns:
            res = pattern.sub(replacement, res)

        # 6. Homophones
        for pattern, replacement in self.homophone_patterns:
            res = pattern.sub(replacement, res)

        # 7. Landmarks (Highways, Metro, Cities)
        for pattern, replacement in self.highway_patterns:
            res = pattern.sub(replacement, res)

        for pattern, replacement in self.metro_compound_patterns:
            res = pattern.sub(replacement, res)

        for pattern, replacement in self.metro_patterns:
            res = pattern.sub(replacement, res)

        for pattern, replacement in self.city_patterns:
            res = pattern.sub(replacement, res)

        # Clean-up: remove double dots (e.g. руб..) and excessive spaces
        res = re.sub(r"руб\.\.+", "руб.", res)
        res = re.sub(r"\s+", " ", res).strip()

        return res
